import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import http from 'node:http';
import {spawn,execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const tool=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../tools/verify-route-reconciliation.mjs');
const git=(cwd,...args)=>execFileSync('git',['-C',cwd,...args],{encoding:'utf8'}).trim();
const run=(args)=>new Promise(resolve=>{
 const child=spawn(process.execPath,[tool,...args],{stdio:['ignore','pipe','pipe']});
 let out='',err='';
 child.stdout.on('data',d=>out+=d);child.stderr.on('data',d=>err+=d);
 child.on('error',error=>resolve({code:-1,err:String(error)}));
 child.on('close',code=>resolve({code,out,err}));
});
test('route reconciliation only records independently verified health and does not rewrite updater receipts',async t=>{
 const temp=fs.mkdtempSync(path.join(os.tmpdir(),'rc-route-proof-'));
 t.after(()=>{assert.match(path.basename(temp),/^rc-route-proof-/);fs.rmSync(temp,{recursive:true,force:true});});
 const repo=path.join(temp,'repo'),state=path.join(temp,'state');
 fs.mkdirSync(repo,{recursive:true});fs.mkdirSync(path.join(state,'routing'),{recursive:true});
 git(repo,'init','-q');fs.writeFileSync(path.join(repo,'README.md'),'fixture');
 git(repo,'add','.');git(repo,'-c','user.name=Fixture','-c','user.email=fixture@example.invalid','commit','-qm','fixture');
 const commit=git(repo,'rev-parse','HEAD');
 const sha='a'.repeat(64),routePath=path.join(state,'routing','default.json');
 const route={schema:1,profile:'default',generation:27,active:{commit,version:'0.10.25',configSha256:sha},previous:null};
 const putRoute=()=>fs.writeFileSync(routePath,JSON.stringify(route,null,2)+'\n');
 putRoute();
 const original={status:'PROMOTED_DRAIN_PENDING',pendingDrains:['default'],commit};
 const last=path.join(state,'last-update.json');fs.writeFileSync(last,JSON.stringify(original));
 let health={ok:true,version:'0.10.25',configSha256:sha,instance:{profile:'default'}};
 const server=http.createServer((req,res)=>{res.setHeader('content-type','application/json');res.end(JSON.stringify(health));});
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 t.after(()=>server.close());
 const port=server.address().port;
 const args=['--state-root',state,'--repo-dir',repo,'--profile','default','--canonical-port',String(port),'--expected-commit',commit];
 const valid=await run([...args,'--write']);
 assert.equal(valid.code,0,valid.err);
 assert.equal(JSON.parse(valid.out).status,'ROUTE_RECONCILED');
 assert.equal(fs.readFileSync(last,'utf8'),JSON.stringify(original),'original updater receipt is immutable');
 const proofPath=path.join(state,'update-logs','route-reconciliations.json');
 const evidence=JSON.parse(fs.readFileSync(proofPath,'utf8'));
 assert.equal(evidence.profiles.default.previousUpdaterStatus,'PROMOTED_DRAIN_PENDING');
 const content=fs.readFileSync(proofPath,'utf8');
 const again=await run([...args,'--write']);
 assert.equal(again.code,0,again.err);
 assert.equal(fs.readFileSync(proofPath,'utf8'),content,'same authoritative state is a no-op');
 route.previous={commit:'b'.repeat(40),port:48831};putRoute();
 assert.match((await run([...args,'--write'])).err,/PREVIOUS_ROUTE_NOT_RETIRED/);
 route.previous=null;putRoute();
 health={...health,configSha256:'b'.repeat(64)};
 assert.match((await run([...args,'--write'])).err,/HEALTH_IDENTITY_MISMATCH/);
 health={...health,configSha256:sha};
 fs.writeFileSync(path.join(state,'retained-backends.json'),JSON.stringify({schema:1,items:[{profile:'default',commit:'b'.repeat(40)}]}));
 assert.match((await run([...args,'--write'])).err,/RETAINED_BACKEND_UNRESOLVED/);
 fs.unlinkSync(path.join(state,'retained-backends.json'));
 assert.match((await run([...args.slice(0,-1),'f'.repeat(40)])).err,/ROUTE_IDENTITY_INVALID/);
 fs.writeFileSync(path.join(repo,'README.md'),'changed fixture');
 assert.match((await run([...args,'--write'])).err,/CONTROL_TRACKED_DIRTY/);
 fs.writeFileSync(path.join(repo,'README.md'),'fixture');
 fs.writeFileSync(path.join(repo,'README.md'),'staged fixture');
 git(repo,'add','README.md');
 assert.match((await run([...args,'--write'])).err,/CONTROL_STAGED_DIRTY/);
 git(repo,'reset','-q','--','README.md');
 fs.writeFileSync(path.join(repo,'README.md'),'fixture'); route.generation=28;putRoute();
 const fresh=await run([...args,'--write']);
 assert.equal(fresh.code,0,fresh.err);
 assert.equal(JSON.parse(fs.readFileSync(proofPath,'utf8')).profiles.default.generation,28);
 assert.equal(fs.readFileSync(last,'utf8'),JSON.stringify(original));
});
